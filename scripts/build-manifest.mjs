// Generates public/materials/{content-pack-*.json, manifest.json} from the
// canonical packs in materials/. Each package is hashed (sha256) AND signed
// (Ed25519); the manifest carries both, plus the base64 SPKI public key used to
// verify signatures at runtime. A fresh keypair is generated per build run, so
// the emitted manifest, signatures, and bundled seed public key are always
// mutually consistent.
//
// Run automatically before `dev` and `build` (see package.json scripts).
import {
  createHash,
  generateKeyPairSync,
  sign as edSign,
} from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'materials');
const outDir = join(root, 'public', 'materials');

mkdirSync(outDir, { recursive: true });

// Build-time signing keypair. Private key never leaves this process; only the
// public key (SPKI DER, base64) is published.
const { privateKey, publicKey } = generateKeyPairSync('ed25519');
const publicKeyBase64 = publicKey
  .export({ type: 'spki', format: 'der' })
  .toString('base64');

function signBase64(text) {
  // Ed25519 in node: pass null algorithm, key object.
  return edSign(null, Buffer.from(text, 'utf8'), privateKey).toString('base64');
}

const files = readdirSync(srcDir).filter((f) => f.endsWith('.json'));
const packages = [];

for (const file of files) {
  const text = readFileSync(join(srcDir, file), 'utf8');
  const parsed = JSON.parse(text);
  const sha256 = createHash('sha256').update(text, 'utf8').digest('hex');
  const signature = signBase64(text);
  writeFileSync(join(outDir, file), text);
  const isDelta = parsed.succeeds !== undefined || parsed.changes !== undefined;
  packages.push({
    packageVersion: parsed.packageVersion,
    url: `materials/${file}`,
    sha256,
    signature,
    kind: isDelta ? 'delta' : 'full',
    ...(parsed.succeeds !== undefined ? { succeeds: parsed.succeeds } : {}),
  });
}

// Order by version string so "latest" is the last (deltas succeed earlier ones).
packages.sort((a, b) =>
  a.packageVersion < b.packageVersion ? -1 : a.packageVersion > b.packageVersion ? 1 : 0,
);
const latest = packages.length > 0 ? packages[packages.length - 1].packageVersion : null;

const manifest = {
  generatedAt: new Date().toISOString(),
  latest,
  publicKey: publicKeyBase64,
  packages,
};
const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;
writeFileSync(join(outDir, 'manifest.json'), manifestText);

// Also emit a bundled seed module so the very first launch works fully offline
// (no network required to see a complete base package) and so the verifying
// public key is pinned into the app, not just fetched.
const bundledDir = join(root, 'src', 'bundled');
mkdirSync(bundledDir, { recursive: true });
const seed = {};
for (const file of files) {
  seed[file] = readFileSync(join(srcDir, file), 'utf8');
}
const seedModule =
  '// AUTO-GENERATED by scripts/build-manifest.mjs — do not edit by hand.\n' +
  '// Bundles the canonical packs + manifest + verifying public key so the\n' +
  '// first launch works fully offline with signature verification intact.\n' +
  `export const bundledPublicKey = ${JSON.stringify(publicKeyBase64)};\n` +
  `export const bundledManifestText = ${JSON.stringify(manifestText)};\n` +
  `export const bundledPackTexts: Record<string, string> = ${JSON.stringify(seed, null, 2)};\n`;
writeFileSync(join(bundledDir, 'seed.ts'), seedModule);

console.log(
  `Wrote signed manifest with ${packages.length} package(s); latest=${latest}`,
);
