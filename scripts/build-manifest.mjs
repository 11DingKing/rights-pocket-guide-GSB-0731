// Generates public/materials/{content-pack-*.json, manifest.json} from the
// canonical packs in materials/. The manifest lists each package version with
// its sha256 so the runtime can verify a download before the atomic switch.
//
// Run automatically before `dev` and `build` (see package.json scripts).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'materials');
const outDir = join(root, 'public', 'materials');

mkdirSync(outDir, { recursive: true });

const files = readdirSync(srcDir).filter((f) => f.endsWith('.json'));
const packages = [];

for (const file of files) {
  const text = readFileSync(join(srcDir, file), 'utf8');
  const parsed = JSON.parse(text);
  const sha256 = createHash('sha256').update(text, 'utf8').digest('hex');
  writeFileSync(join(outDir, file), text);
  const isDelta = parsed.succeeds !== undefined || parsed.changes !== undefined;
  packages.push({
    packageVersion: parsed.packageVersion,
    url: `materials/${file}`,
    sha256,
    kind: isDelta ? 'delta' : 'full',
    ...(parsed.succeeds !== undefined ? { succeeds: parsed.succeeds } : {}),
  });
}

// Order by version string so "latest" is the last (deltas succeed earlier ones).
packages.sort((a, b) =>
  a.packageVersion < b.packageVersion ? -1 : a.packageVersion > b.packageVersion ? 1 : 0,
);
const latest = packages.length > 0 ? packages[packages.length - 1].packageVersion : null;

const manifest = { generatedAt: new Date().toISOString(), latest, packages };
writeFileSync(join(outDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);

// Also emit a bundled seed module so the very first launch works fully offline
// (no network required to see a complete base package).
const bundledDir = join(root, 'src', 'bundled');
mkdirSync(bundledDir, { recursive: true });
const seed = {};
for (const file of files) {
  seed[file] = readFileSync(join(srcDir, file), 'utf8');
}
const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;
const seedModule =
  '// AUTO-GENERATED by scripts/build-manifest.mjs — do not edit by hand.\n' +
  '// Bundles the canonical packs + manifest so the first launch works offline.\n' +
  `export const bundledManifestText = ${JSON.stringify(manifestText)};\n` +
  `export const bundledPackTexts: Record<string, string> = ${JSON.stringify(seed, null, 2)};\n`;
writeFileSync(join(bundledDir, 'seed.ts'), seedModule);

console.log(`Wrote manifest with ${packages.length} package(s); latest=${latest}`);
